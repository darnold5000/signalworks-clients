function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function inlineFormat(value: string): string {
  return escapeHtml(value).replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>");
}

function markdownToHtml(markdown: string): string {
  const lines = markdown.split("\n");
  const parts: string[] = [];
  let list: string[] = [];

  const flushList = () => {
    if (list.length === 0) return;
    parts.push(
      `<ul>\n${list.map((item) => `<li>${item}</li>`).join("\n")}\n</ul>`,
    );
    list = [];
  };

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) {
      flushList();
      continue;
    }
    if (trimmed === "---") {
      flushList();
      parts.push("<hr />");
      continue;
    }
    if (trimmed.startsWith("## ")) {
      flushList();
      parts.push(`<h2>${inlineFormat(trimmed.slice(3))}</h2>`);
      continue;
    }
    if (trimmed.startsWith("# ")) {
      flushList();
      parts.push(`<h1>${inlineFormat(trimmed.slice(2))}</h1>`);
      continue;
    }
    if (trimmed.startsWith("- ")) {
      list.push(inlineFormat(trimmed.slice(2)));
      continue;
    }
    flushList();
    parts.push(`<p>${inlineFormat(trimmed)}</p>`);
  }

  flushList();
  return parts.join("\n");
}

export function formatLegalEffectiveDate(date: Date = new Date()): string {
  return date.toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
    timeZone: "UTC",
  });
}

